// Funções utilitárias seguras com fallback
export function getSectionStyle(projectId) {
  return SECTION_STYLES[projectId] || "bg-[#FAFAFA] text-neutral-900 border-neutral-100";
}

export function getRadialGlow(projectId) {
  return RADIAL_GLOWS[projectId] || "opacity-0";
}

export function getSectionTagColor(projectId) {
  return SECTION_TAG_COLORS[projectId] || "text-emerald-700";
}

export function getSectionTitleColor(projectId) {
  return SECTION_TITLE_COLORS[projectId] || "text-neutral-900";
}

export function getNavButtonStyle(projectId) {
  return NAV_BUTTON_STYLES[projectId] || "border-neutral-200 bg-white text-neutral-700 hover:bg-neutral-50";
}

export function getCounterColor(projectId) {
  return COUNTER_COLORS[projectId] || "text-neutral-500";
}

export function getCardContainerStyle(projectId) {
  return CARD_CONTAINER_STYLES[projectId] || "border-neutral-200 bg-white text-neutral-900";
}

export function getPillStyle(projectId, isCurrent, activeProjectId) {
  if (isCurrent) {
    return PILL_ACTIVE_STYLES[projectId] || "bg-neutral-900 text-white font-bold shadow-sm scale-105";
  }
  return PILL_INACTIVE_STYLES[activeProjectId] || "bg-white text-neutral-600 border border-neutral-200 hover:bg-neutral-50";
}

export function getPillDotColor(projectId, isCurrent) {
  return PILL_DOT_COLORS[projectId] || (isCurrent ? "bg-white" : "bg-neutral-300");
}

